mod data;
mod substituter;

use std::{
    collections::HashMap,
    fs::File,
    io::Write,
    path::{Path, PathBuf},
    process::Command,
    time::Instant,
};

use clap::{Args, Parser, Subcommand};
use data::{PackageInfo, Registry};
use eyre::{Context, Result};
use rippkgs::Package;
use rusqlite::OpenFlags;

#[derive(Debug, Parser)]
#[clap(about = "Generate an index for use with the rippkgs cli")]
struct Opts {
    #[clap(subcommand)]
    cmd: Subcmd,
}

#[derive(Debug, Subcommand)]
enum Subcmd {
    /// Generate an index from a registry JSON file
    Registry(ImportRegistry),
    /// Generate an index from a nixpkgs expression
    Nixpkgs(IndexNixpkgs),
}

#[derive(Debug, Args)]
struct ImportRegistry {
    /// The registry to import. This should be generated by calling `genRegistry` from the flake
    /// library.
    registry: PathBuf,

    /// The location to write the saved index to.
    #[clap(short, long, default_value = "rippkgs-index.sqlite")]
    output: PathBuf,

    /// Check output paths in this binary cache and record their availability.
    #[clap(long)]
    substituter: Option<String>,
}

#[derive(Debug, Args)]
struct IndexNixpkgs {
    /// Optional location to save the generated registry to.
    #[clap(short = 'r', long)]
    save_registry: Option<PathBuf>,

    /// Optional expression to use for the `config` argument to `import <nixpkgs>`.
    #[clap(short = 'a', long, default_value = "{}")]
    nixpkgs_arg: String,

    /// The location of Nixpkgs on-disk to index. If omitted, will import `<nixpkgs>` without
    /// passing the `-I` flag to nix.
    nixpkgs: Option<PathBuf>,

    /// The location to write the saved index to.
    #[clap(short, long, default_value = "rippkgs-index.sqlite")]
    output: PathBuf,

    /// Check output paths in this binary cache and record their availability.
    #[clap(long)]
    substituter: Option<String>,
}

fn main() -> Result<()> {
    let opts = Opts::parse();

    let output = match &opts.cmd {
        Subcmd::Registry(opts) => opts.output.as_path(),
        Subcmd::Nixpkgs(opts) => opts.output.as_path(),
    };

    match std::fs::remove_file(output) {
        Ok(()) => (),
        Err(err) if err.kind() == std::io::ErrorKind::NotFound => (),
        Err(err) => Err(err).context("removing previous index db")?,
    }

    let registry = match &opts.cmd {
        Subcmd::Registry(opts) => import_registry(opts).context("importing registry")?,
        Subcmd::Nixpkgs(opts) => index_nixpkgs(opts).context("indexing nixpkgs")?,
    };

    let substituter = match &opts.cmd {
        Subcmd::Registry(opts) => opts.substituter.as_deref(),
        Subcmd::Nixpkgs(opts) => opts.substituter.as_deref(),
    };
    write_index(output, registry, substituter).context("writing index")?;

    Ok(())
}

fn write_index(index: &Path, registry: Registry, substituter: Option<&str>) -> Result<()> {
    let cached = substituter.map(|url| substituter::availability(&registry, url));
    let mut conn = rusqlite::Connection::open_with_flags(
        index,
        OpenFlags::SQLITE_OPEN_CREATE
            | OpenFlags::SQLITE_OPEN_READ_WRITE
            | OpenFlags::SQLITE_OPEN_NO_MUTEX,
    )
    .context("connecting to index database")?;

    conn.execute(Package::create_table(), [])
        .context("creating table in database")?;

    let start = Instant::now();
    let tx = conn.transaction().context("starting transaction")?;

    {
        let mut create_cached_row_query = if cached.is_some() {
            tx.execute(
                "CREATE TABLE cached_packages (attribute TEXT NOT NULL PRIMARY KEY)",
                [],
            )
            .context("creating cached packages table")?;
            Some(
                tx.prepare("INSERT INTO cached_packages (attribute) VALUES (?1)")
                    .context("preparing cached packages INSERT query")?,
            )
        } else {
            None
        };
        let mut create_row_query = tx
            .prepare(
                r#"
    INSERT INTO packages (attribute, name, version, storePaths, propagatedBuildInputs, propagatedNativeBuildInputs, description, long_description)
    VALUES (?, ?, ?, ?, ?, ?, ?, ?)
                "#,
            )
            .context("preparing INSERT query")?;

        registry
            .into_iter()
            .map(|(attr, info)| info.into_rippkgs_package(attr))
            .try_for_each(
                |Package {
                     attribute,
                     name,
                     version,
                     store_paths,
                     propagated_build_inputs,
                     propagated_native_build_inputs,
                     description,
                     long_description,
                     score: _score, // score not included in the database
                     ..
                 }| {
                    let is_cached = store_paths
                        .as_ref()
                        .and_then(|paths| paths.get("out"))
                        .and_then(|path| cached.as_ref()?.get(path).copied())
                        .flatten()
                        == Some(true);
                    if is_cached {
                        if let Some(query) = create_cached_row_query.as_mut() {
                            query
                                .execute(rusqlite::params![&attribute])
                                .context("inserting cached package")?;
                        }
                    }
                    let store_paths = store_paths
                        .map(|store_paths| serde_json::to_string(&store_paths))
                        .transpose()?;
                    let propagated_build_inputs = propagated_build_inputs
                        .map(|propagated_build_inputs| {
                            serde_json::to_string(&propagated_build_inputs)
                        })
                        .transpose()?;
                    let propagated_native_build_inputs = propagated_native_build_inputs
                        .map(|propagated_native_build_inputs| {
                            serde_json::to_string(&propagated_native_build_inputs)
                        })
                        .transpose()?;
                    create_row_query
                        .execute(rusqlite::params![
                            attribute,
                            name,
                            version,
                            store_paths,
                            propagated_build_inputs,
                            propagated_native_build_inputs,
                            description,
                            long_description
                        ])
                        .context("inserting package into database")
                        .map(|_| ())
                },
            )?;
    }

    tx.commit().context("committing database")?;

    println!(
        "wrote index in {:.4} seconds",
        start.elapsed().as_secs_f64()
    );

    Ok(())
}

fn index_nixpkgs(
    IndexNixpkgs {
        save_registry,
        nixpkgs_arg,
        nixpkgs,
        ..
    }: &IndexNixpkgs,
) -> Result<Registry> {
    let apply_arg = format!(
        r#"
genRegistry:

let pkgs = import <nixpkgs> {nixpkgs_arg};
    genRegistry' = genRegistry pkgs;
in genRegistry' pkgs
        "#,
    );

    let mut args = vec![
        "eval",
        "--impure",
        "--json",
        "--expr",
        include_str!(concat!(env!("CARGO_MANIFEST_DIR"), "/lib/genRegistry.nix")),
        "--apply",
        apply_arg.as_str(),
    ];

    let mut nixpkgs_include_arg = String::new();
    if let Some(nixpkgs) = nixpkgs.as_ref() {
        nixpkgs_include_arg.push_str(format!("nixpkgs={}", nixpkgs.display()).as_str());
        args.push("-I");
        args.push(nixpkgs_include_arg.as_str());
    }

    let start = Instant::now();

    let output = Command::new("nix")
        .args(args.iter())
        .output()
        .with_context(|| format!("getting nixpkgs packages from {}", "nixpkgs"))?;

    println!(
        "evaluated registry in {:.4} seconds",
        start.elapsed().as_secs_f64()
    );

    if !output.status.success() {
        panic!(
            "`nix eval` failed: {}",
            String::from_utf8_lossy(&output.stderr)
        );
    }

    if let Some(registry) = save_registry {
        File::options()
            .write(true)
            .truncate(true)
            .create(true)
            .open(registry)
            .context("opening registry file")?
            .write(&output.stdout)
            .context("writing registry file")?;
    }

    let start = Instant::now();
    let res = serde_json::from_slice(&output.stdout).context("reading registry JSON");
    println!(
        "parsed registry in {:.4} seconds",
        start.elapsed().as_secs_f64()
    );

    res
}

fn import_registry(ImportRegistry { registry, .. }: &ImportRegistry) -> Result<Registry> {
    let f = File::options()
        .read(true)
        .open(registry)
        .context("opening registry file")?;

    let start = Instant::now();
    let res = serde_json::from_reader::<_, HashMap<String, PackageInfo>>(f)
        .context("reading registry JSON")?;

    println!(
        "parsed registry in {:.4} seconds",
        start.elapsed().as_secs_f64()
    );

    Ok(res)
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::io::{Read, Write};
    use std::net::TcpListener;
    use std::thread;
    use std::time::{Duration, Instant, SystemTime, UNIX_EPOCH};

    fn registry() -> Registry {
        serde_json::from_str(
            r#"{
                "hit": {"storePaths": {"out": "00000000000000000000000000000000-hit"}},
                "miss": {"storePaths": {"out": "11111111111111111111111111111111-miss"}},
                "timeout": {"storePaths": {"out": "22222222222222222222222222222222-timeout"}}
            }"#,
        )
        .unwrap()
    }

    const MAIN_PACKAGES_DDL: &str = "CREATE TABLE packages (
    attribute TEXT NOT NULL,
    name TEXT,
    version TEXT,
    storePaths TEXT,
    propagatedBuildInputs TEXT,
    propagatedNativeBuildInputs TEXT,
    description TEXT,
    long_description TEXT,
    PRIMARY KEY (attribute)
)";

    fn tables(db: &rusqlite::Connection) -> Vec<String> {
        let mut query = db
            .prepare("SELECT name FROM sqlite_master WHERE type = 'table' ORDER BY name")
            .unwrap();
        query
            .query_map([], |row| row.get(0))
            .unwrap()
            .map(Result::unwrap)
            .collect()
    }

    #[test]
    fn index_records_cache_hits_misses_and_timeouts() {
        let listener = TcpListener::bind("127.0.0.1:0").unwrap();
        let url = format!("http://{}", listener.local_addr().unwrap());
        let server = thread::spawn(move || {
            listener.set_nonblocking(true).unwrap();
            let mut handlers = Vec::new();
            let deadline = Instant::now() + Duration::from_secs(8);
            while handlers.len() < 4 && Instant::now() < deadline {
                match listener.accept() {
                    Ok((mut stream, _)) => handlers.push(thread::spawn(move || {
                        let mut request = [0; 4096];
                        let count = stream.read(&mut request).unwrap();
                        let request = String::from_utf8_lossy(&request[..count]);
                        if request.contains("/22222222222222222222222222222222.narinfo") {
                            thread::sleep(Duration::from_millis(2400));
                        } else {
                            let status =
                                if request.contains("/00000000000000000000000000000000.narinfo") {
                                    "200 OK"
                                } else {
                                    "404 Not Found"
                                };
                            write!(stream, "HTTP/1.1 {status}\r\nContent-Length: 0\r\n\r\n")
                                .unwrap();
                        }
                    })),
                    Err(err) if err.kind() == std::io::ErrorKind::WouldBlock => {
                        thread::sleep(Duration::from_millis(10));
                    }
                    Err(err) => panic!("accept failed: {err}"),
                }
            }
            assert_eq!(handlers.len(), 4, "expected a retry after the timeout");
            for handler in handlers {
                handler.join().unwrap();
            }
        });

        let now = SystemTime::now()
            .duration_since(UNIX_EPOCH)
            .unwrap()
            .as_nanos();
        let path = std::env::temp_dir().join(format!("rippkgs-{now}.sqlite"));
        write_index(&path, registry(), Some(&url)).unwrap();
        server.join().unwrap();

        let db = rusqlite::Connection::open(&path).unwrap();
        assert_eq!(tables(&db), vec!["cached_packages", "packages"]);
        let package_schema: String = db
            .query_row(
                "SELECT sql FROM sqlite_master WHERE name = 'packages'",
                [],
                |row| row.get(0),
            )
            .unwrap();
        assert_eq!(package_schema, MAIN_PACKAGES_DDL);
        let hits: Vec<String> = {
            let mut query = db
                .prepare("SELECT attribute FROM cached_packages ORDER BY attribute")
                .unwrap();
            query
                .query_map([], |row| row.get(0))
                .unwrap()
                .map(Result::unwrap)
                .collect()
        };
        assert_eq!(hits, vec!["hit"]);
        drop(db);
        std::fs::remove_file(path).unwrap();
    }

    #[test]
    fn indexing_without_substituter_preserves_main_schema() {
        let now = SystemTime::now()
            .duration_since(UNIX_EPOCH)
            .unwrap()
            .as_nanos();
        let path = std::env::temp_dir().join(format!("rippkgs-no-cache-{now}.sqlite"));
        write_index(&path, registry(), None).unwrap();
        let db = rusqlite::Connection::open(&path).unwrap();
        let package_schema: String = db
            .query_row(
                "SELECT sql FROM sqlite_master WHERE name = 'packages'",
                [],
                |row| row.get(0),
            )
            .unwrap();
        assert_eq!(package_schema, MAIN_PACKAGES_DDL);
        assert_eq!(tables(&db), vec!["packages"]);
        let rows: Vec<(String, String)> = {
            let mut query = db
                .prepare("SELECT attribute, storePaths FROM packages ORDER BY attribute")
                .unwrap();
            query
                .query_map([], |row| Ok((row.get(0)?, row.get(1)?)))
                .unwrap()
                .map(Result::unwrap)
                .collect()
        };
        assert_eq!(
            rows,
            vec![
                (
                    "hit".to_string(),
                    r#"{"out":"00000000000000000000000000000000-hit"}"#.to_string()
                ),
                (
                    "miss".to_string(),
                    r#"{"out":"11111111111111111111111111111111-miss"}"#.to_string()
                ),
                (
                    "timeout".to_string(),
                    r#"{"out":"22222222222222222222222222222222-timeout"}"#.to_string()
                )
            ]
        );
        drop(db);
        std::fs::remove_file(path).unwrap();
    }
}
